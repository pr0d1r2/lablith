#[test]
fn verify_cache_asks_the_cache_for_every_system() -> io::Result<()> {
    let args = ["c", "hk", "x86_64-linux", "aarch64-darwin"];
    let ran = run("vc-ok", "verify-cache.sh", &args, &[])?;
    assert_eq!(ran.code, Some(0), "{}", ran.stderr);
    let got = calls(&ran);
    assert!(got.contains(&"nix eval --raw .#packages.x86_64-linux.hk"));
    for hash in ["x86_64linux", "aarch64darwin"] {
        let url = format!("https://c.cachix.org/{hash}.narinfo");
        let asked = got
            .iter()
            .any(|c| c.starts_with("curl ") && c.ends_with(&url));
        assert!(asked, "{url} not asked in {got:?}");
    }
    Ok(())
}

