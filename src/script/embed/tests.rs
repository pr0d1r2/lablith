//! The seeded scripts run with `bash` in a scratch directory against stub
//! `git`, `nix`, `curl` and `lablith` placed first on PATH, each recording
//! the calls it receives (src/script:T20). bats is not in the dev shell,
//! so the scripts are exercised from here, as in actlith.

use super::{Script, scripts};
use std::fs;
use std::io;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const STUB: &str = include_str!("../../../tests/fixtures/script/stub.sh");
const TOOLS: [&str; 4] = ["git", "nix", "curl", "lablith"];
const HEADER: &str = "# generated by lablith gen from .lablith; do not edit\n";
const BEFORE: &str = "1111111111111111111111111111111111111111";
const AFTER: &str = "abcdef0123456789abcdef0123456789abcdef01";

/// A hook's git environment; dropped so nothing a script runs can reach
/// the repository the tests run in.
const GIT_ENV: [&str; 6] = [
    "GIT_DIR",
    "GIT_WORK_TREE",
    "GIT_INDEX_FILE",
    "GIT_OBJECT_DIRECTORY",
    "GIT_ALTERNATE_OBJECT_DIRECTORIES",
    "GIT_COMMON_DIR",
];

/// The fake token the open-mr tests set, and its basic-auth header.
const TOKEN: &str = "glpat-test";
const AUTH: &str = "http.extraHeader=Authorization: Basic \
    b2F1dGgyOmdscGF0LXRlc3Q=";

/// The GitLab job variables open-mr.sh reads.
const CI: [(&str, &str); 6] = [
    ("LABLITH_TOKEN", TOKEN),
    ("CI_SERVER_URL", "https://gitlab.example"),
    ("CI_PROJECT_PATH", "group/project"),
    ("CI_DEFAULT_BRANCH", "main"),
    ("CI_API_V4_URL", "https://gitlab.example/api/v4"),
    ("CI_PROJECT_ID", "7"),
];

/// update-pins.sh's calls on a new pin, among others.
const PINS_CALLS: [&str; 5] = [
    "nix build --no-link --print-build-logs .#default",
    "lablith pin",
    "lablith gen",
    "git add -- flake.lock .lablith .gitlab-ci.yml .gitlab/ci scripts/lablith",
    " push https://gitlab.example/group/project.git \
     HEAD:refs/heads/pins/nixpkgs-abcdef012345",
];

/// What a script run left behind: exit code, recorded calls, stderr.
struct Ran {
    code: Option<i32>,
    log: String,
    stderr: String,
}

fn bash() -> io::Result<PathBuf> {
    on_path("bash")
}

/// The first `tool` on this process's PATH (the stubs are not on it).
fn on_path(tool: &str) -> io::Result<PathBuf> {
    let path = std::env::var_os("PATH").unwrap_or_default();
    std::env::split_paths(&path)
        .map(|dir| dir.join(tool))
        .find(|file| file.is_file())
        .ok_or_else(|| io::Error::other(format!("no {tool} on PATH")))
}

/// A fresh directory holding every seeded script at its published path.
fn scratch(name: &str) -> io::Result<PathBuf> {
    let id = std::process::id();
    let dir = std::env::temp_dir().join(format!("lablith-script-{id}-{name}"));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(dir.join("bin"))?;
    for (path, bytes) in scripts() {
        let file = dir.join(path);
        if let Some(parent) = file.parent() {
            fs::create_dir_all(parent)?;
        }
        fs::write(file, bytes)?;
    }
    Ok(dir)
}

fn stubs(dir: &Path, bash: &Path) -> io::Result<()> {
    let text = format!("#!{}\n{STUB}", bash.display());
    for tool in TOOLS {
        let file = dir.join("bin").join(tool);
        fs::write(&file, &text)?;
        fs::set_permissions(&file, fs::Permissions::from_mode(0o755))?;
    }
    Ok(())
}

fn search_path(dir: &Path) -> io::Result<std::ffi::OsString> {
    let path = std::env::var_os("PATH").unwrap_or_default();
    let rest = std::env::split_paths(&path);
    std::env::join_paths(std::iter::once(dir.join("bin")).chain(rest))
        .map_err(io::Error::other)
}

/// `bash` without the hook's git environment (`GIT_ENV`).
fn bare(bash: &Path) -> Command {
    let mut cmd = Command::new(bash);
    for var in GIT_ENV {
        cmd.env_remove(var);
    }
    cmd
}

/// Run `scripts/lablith/<script>` with `args` and extra `env`.
fn run(
    name: &str,
    script: &str,
    args: &[&str],
    env: &[(&str, &str)],
) -> io::Result<Ran> {
    run_in(&scratch(name)?, script, args, env)
}

/// Run `scripts/lablith/<script>` in `dir`, prepared by `scratch`.
fn run_in(
    dir: &Path,
    script: &str,
    args: &[&str],
    env: &[(&str, &str)],
) -> io::Result<Ran> {
    let bash = bash()?;
    stubs(dir, &bash)?;
    let log = dir.join("calls.log");
    fs::write(&log, "")?;
    let out = bare(&bash)
        .arg(format!("scripts/lablith/{script}"))
        .args(args)
        .current_dir(dir)
        .env("PATH", search_path(dir)?)
        .env("STUB_LOG", &log)
        .envs(env.iter().copied())
        .output()?;
    ran(&out, &log)
}

fn ran(out: &Output, log: &Path) -> io::Result<Ran> {
    let stderr = String::from_utf8_lossy(&out.stderr).into_owned();
    let log = fs::read_to_string(log)?;
    Ok(Ran {
        code: out.status.code(),
        log,
        stderr,
    })
}

fn calls(ran: &Ran) -> Vec<&str> {
    ran.log.lines().collect()
}

fn update_pins(name: &str, args: &[&str], env: &[(&str, &str)]) -> Ran {
    let revs = [("STUB_REV_BEFORE", BEFORE), ("STUB_REV_AFTER", AFTER)];
    let env: Vec<_> = revs.iter().chain(&CI).chain(env).copied().collect();
    run(name, "update-pins.sh", args, &env).unwrap_or(Ran {
        code: None,
        log: String::new(),
        stderr: String::new(),
    })
}

fn mr(name: &str, args: &[&str], env: &[(&str, &str)]) -> io::Result<Ran> {
    let env: Vec<_> = CI.iter().chain(env).copied().collect();
    run(name, "open-mr.sh", args, &env)
}

#[test]
fn scripts_are_published_under_scripts_lablith_sorted() {
    let paths: Vec<_> = scripts().iter().map(|(path, _)| *path).collect();
    let want = [
        "scripts/lablith/cachix.sh",
        "scripts/lablith/open-mr.sh",
        "scripts/lablith/update-pins.sh",
        "scripts/lablith/upstream.sh",
        "scripts/lablith/verify-cache.sh",
    ];
    assert_eq!(paths, want);
    assert_eq!(Script::OpenMr.path(), "scripts/lablith/open-mr.sh");
}

