//! The seeded scripts, embedded from the real files beside this module
//! and prefixed with the generated header (`src/gen:V5`).

/// One seeded script a kind may call.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) enum Script {
    /// `cache-push.sh`: run a command, pushing to a `## caches` cache
    /// with its own push secret (`src/cache:V82`).
    CachePush,
    /// `cache-read.sh`: the nix settings of a cache with a secret url or
    /// key (`src/cache:V81`).
    CacheRead,
    /// `cachix.sh`: run a command, pushing to the row's cache when allowed.
    Cachix,
    /// `https-verify.sh`: kind `build` on an https cache (`src/cache:V84`).
    HttpsVerify,
    /// `open-mr.sh`: commit, push a branch, open a merge request.
    OpenMr,
    /// `runner-system.sh`: stop unless the runner is the job's system
    /// (`src/kind:V77`); first in every nix job.
    RunnerSystem,
    /// `update-pins.sh`: kind `update-pins`.
    UpdatePins,
    /// `upstream.sh`: kind `upstream`.
    Upstream,
    /// `verify-cache.sh`: kind `build`.
    VerifyCache,
}

impl Script {
    /// The published path, `scripts/lablith/<name>.sh`.
    pub(crate) fn path(self) -> &'static str {
        self.file().0
    }

    /// `(published path, header + file)`.
    pub(crate) fn file(self) -> (&'static str, &'static str) {
        match self {
            Self::CachePush => seeded!("cache-push.sh"),
            Self::CacheRead => seeded!("cache-read.sh"),
            Self::Cachix => seeded!("cachix.sh"),
            Self::HttpsVerify => seeded!("https-verify.sh"),
            Self::OpenMr => seeded!("open-mr.sh"),
            Self::RunnerSystem => seeded!("runner-system.sh"),
            Self::UpdatePins => seeded!("update-pins.sh"),
            Self::Upstream => seeded!("upstream.sh"),
            Self::VerifyCache => seeded!("verify-cache.sh"),
        }
    }

    /// The scripts this one runs, which must be published beside it.
    pub(crate) fn calls(self) -> &'static [Self] {
        match self {
            Self::UpdatePins | Self::Upstream => &[Self::OpenMr],
            _ => &[],
        }
    }
}

/// `(published path, header + file)` for one script beside this module.
macro_rules! seeded {
    ($name:literal) => {
        (
            concat!("scripts/lablith/", $name),
            concat!(
                "# generated by lablith gen from .lablith; do not edit\n",
                include_str!($name)
            ),
        )
    };
}
use seeded;

/// Every seeded script, sorted by path.
pub(crate) fn scripts() -> [(&'static str, &'static str); 9] {
    [
        Script::CachePush,
        Script::CacheRead,
        Script::Cachix,
        Script::HttpsVerify,
        Script::OpenMr,
        Script::RunnerSystem,
        Script::UpdatePins,
        Script::Upstream,
        Script::VerifyCache,
    ]
    .map(Script::file)
}

