use super::{Job, Rule, Stage, When, row_document};
use crate::core::yaml::{Comment, Text};
use crate::pin::Image;
use crate::pipeline::{eq, var};

fn nix() -> Image {
    Image {
        name: "nixos/nix".into(),
        version: "2.35.3".into(),
        digest: "sha256:ab".into(),
    }
}

/// The smallest job: no optional key.
fn bare() -> Job {
    Job {
        name: "ci:gate:x86_64-linux".into(),
        comment: None,
        stage: Stage::Gate,
        image: nix(),
        tags: vec!["nix".into(), "x86_64-linux".into()],
        timeout: 30,
        interruptible: true,
        resource_group: None,
        needs: Vec::new(),
        rules: Vec::new(),
        variables: Vec::new(),
        script: vec![Text::lit("nix develop --command hk check --all --check")],
    }
}

const HEADER: &str =
    "# generated by lablith gen from .lablith; do not edit\n---\n";

#[test]
fn a_bare_job_writes_every_required_key_in_order() {
    let want = format!(
        "{HEADER}'ci:gate:x86_64-linux':\n  stage: gate\n  image: \
         'nixos/nix@sha256:ab'  # 2.35.3\n  tags: [nix, x86_64-linux]\n  \
         timeout: '30 minutes'\n  interruptible: true\n  script: [nix \
         develop --command hk check --all --check]\n"
    );
    assert_eq!(row_document(&[bare()]), want);
}

/// Every optional key set.
fn full() -> Job {
    let schedule = eq("CI_PIPELINE_SOURCE", "schedule");
    Job {
        comment: Some(Comment::new("why")),
        interruptible: false,
        resource_group: Some("lablith-pins".into()),
        needs: vec!["ci:build".into()],
        rules: vec![
            rule(Some(schedule), When::Never),
            rule(None, When::OnSuccess),
        ],
        variables: vec![("GIT_DEPTH", Text::lit("0")), ("X", var("Y"))],
        ..bare()
    }
}

fn rule(cond: Option<Text>, when: When) -> Rule {
    Rule {
        cond,
        when: Some(when),
    }
}

const FULL: &str = "# why\n'ci:gate:x86_64-linux':\n  stage: gate\n  \
    image: 'nixos/nix@sha256:ab'  # 2.35.3\n  tags: [nix, x86_64-linux]\n  \
    timeout: '30 minutes'\n  interruptible: false\n  resource_group: \
    lablith-pins\n  needs: ['ci:build']\n  rules:\n    - if: \
    '$CI_PIPELINE_SOURCE == \"schedule\"'\n      when: never\n    - \
    when: on_success\n  variables:\n    GIT_DEPTH: '0'\n    X: $Y\n  \
    script: [nix develop --command hk check --all --check]\n";

#[test]
fn every_optional_key_follows_in_order() {
    assert_eq!(row_document(&[full()]), format!("{HEADER}{FULL}"));
}

#[test]
fn jobs_of_a_row_are_separated_by_a_blank_line() {
    let second = Job {
        name: "ci:gate:aarch64-linux".into(),
        ..bare()
    };
    let out = row_document(&[bare(), second]);
    assert!(
        out.contains("check]\n\n'ci:gate:aarch64-linux':\n"),
        "{out}"
    );
}

#[test]
fn stages_are_fixed_and_ordered() {
    let names: Vec<&str> = Stage::ALL.iter().map(|s| s.name()).collect();
    assert_eq!(names, ["gate", "build", "verify", "bump"]);
}
